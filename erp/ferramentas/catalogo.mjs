const PARENTESE_TECNICO =
  /ams\b|\b(impress|print|vers[aã]o|version|a1|mini|multi|camada|layer|escala|scale|suporte|support|partes|pe[çc]as|marca d|3mf|stl)/i;

function capitalizar(palavra, primeira) {
  // Sigla fica como está: tem número (GT3, M4, 1/24) ou é curta e sem vogal (RS, GT, BMW, SVJ).
  if (/\d/.test(palavra) || (palavra.length <= 4 && !/[aeiouáéíóúâêôãõ]/i.test(palavra)))
    return palavra;
  const minuscula = palavra.toLocaleLowerCase("pt-BR");
  if (!primeira && PALAVRAS_MINUSCULAS.has(minuscula)) return minuscula;
  return minuscula.charAt(0).toLocaleUpperCase("pt-BR") + minuscula.slice(1);
}

/** Nome em caixa alta (mais de 70% das letras maiúsculas e pelo menos 2 palavras) vira título. */
function corrigirCaixa(nome) {
  const letras = nome.replace(/[^\p{L}]/gu, "");
  const maiusculas = letras.replace(/[^\p{Lu}]/gu, "");
  if (letras.length < 6 || maiusculas.length / letras.length < 0.7 || !/\s/.test(nome.trim()))
    return nome;
  return nome
    .split(/(\s+)/)
    .map((parte, i) => (/\s/.test(parte) ? parte : capitalizar(parte, i === 0)))
    .join("");
}

const AMS =
  /[/+]?\s*\b(n[aã]o\s+((é\s+)?(necess[aá]rio|precisa\s+de)\s+)?|livre\s+de\s+|com\s+e\s+sem\s+|sem\s+|no\s*|non\s+|without\s+|com\s+)?ams\b(\s+(necess[aá]rio|completo|required|lite))?/gi;
const RUIDO = [
  /[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Hangul}丨]+/gu,
  /[【】]/g,
  /\[[^\]]*\]/g,
  /\b(sem|livre\s+de|without|no)\s+suportes?\b/gi,
  /\b(multi[\s-]?(partes?|parts?|pe[çc]as?|cor(es)?|colou?r(ido)?)|multicolorid[oa]|multicor(es)?|multicolou?r)\b/gi,
  /\b(3mf|stl|fdm)\b/gi,
  /\bimpress[aã]o\s+(em\s+)?(m[uú]ltiplas\s+)?(partes|pe[çc]as)(\s+separadas)?(?![\p{L}])/giu,
  /\buse with caution!?/gi,
  /~?\s*\d+(,\d+)?\s?(mm|cm)\b(\s+de\s+altura(\s+na\s+base)?)?/gi,
  /\b\d+%/g,
  /\*/g,
];

function limparParentese(todo, dentro) {
  return !dentro.replace(/[\s/+,.:-]/g, "") || dentro.length > 30 || PARENTESE_TECNICO.test(dentro)
    ? " "
    : todo;
}

export function limparNome(titulo) {
  let nome = String(titulo ?? "");
  nome = nome.split("|")[0];
  for (const r of RUIDO) nome = nome.replace(r, " ");
  nome = nome.replace(/\(([^)]*)\)/g, limparParentese);
  nome = nome.replace(AMS, " ");
  nome = nome.replace(/\(([^)]*)\)/g, limparParentese);
  nome = nome.replace(/["“”]\s*["“”]/g, " ");
  // Travessão, hífen solto e dois-pontos viram um separador só; "1:19" e "Porta-lápis" ficam.
  nome = nome.replace(/\s*[–—]+\s*|\s+-+(?=\s|$)|-\s+|\s*:\s+|\s+:\s*/g, "§");
  nome = nome.replace(/(\s*§)+\s*/g, ": ");
  nome = aparar(nome.replace(/\s+/g, " "));
  nome = aparar(encurtar(corrigirCaixa(nome).trim()));
  return nome.charAt(0).toLocaleUpperCase("pt-BR") + nome.slice(1);
}

const PREPOSICAO_FINAL = new RegExp(`(\\s+(${[...PALAVRAS_MINUSCULAS].join("|")}))+$`, "i");

/** Tira separador, preposição e "impressão" que sobram nas pontas. */
function aparar(nome) {
  return nome
    .replace(/^[\s:,/–—-]+|[\s:,/–—+-]+$/g, "")
    .replace(PREPOSICAO_FINAL, "")
    .replace(/\s+impress[aã]o$/i, "")
    .trim();
}

export const NOME_MAXIMO = 90;

/** Nome longo é cortado no último separador (se sobrar um nome razoável) ou na última palavra inteira. */
function encurtar(nome) {
  if (nome.length <= NOME_MAXIMO) return nome;
  const trecho = nome.slice(0, NOME_MAXIMO + 1);
  const separador = Math.max(
    trecho.lastIndexOf(":"),
    trecho.lastIndexOf(","),
    trecho.lastIndexOf("."),
  );
  if (separador >= 30) return trecho.slice(0, separador);
  return trecho.slice(0, trecho.lastIndexOf(" "));
}

