/** Capa já redimensionada pela CDN (800 px, webp); o importador ainda recorta e comprime. */
export function urlCapa(capa) {
  const url = new URL(capa);
  if (url.hostname !== CDN) throw new Error(`capa fora da CDN do MakerWorld: ${url.hostname}`);
  return `${url.origin}${url.pathname}?x-oss-process=image/resize,w_800/format,webp`;
}

